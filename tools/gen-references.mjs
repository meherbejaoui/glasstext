#!/usr/bin/env node
/**
 * Render src/citations.js into REFERENCES.md.
 *
 * The citations live in code because that is where they are used; this script
 * projects them into a document for people reading the repository. Generating
 * rather than duplicating means a reference can never drift out of sync with
 * the metric that depends on it.
 *
 * CI runs this with --check to fail the build if REFERENCES.md is stale.
 *
 * Usage:
 *   node tools/gen-references.mjs           # write REFERENCES.md
 *   node tools/gen-references.mjs --check    # exit 1 if it would change
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CITATIONS } from '../src/citations.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'REFERENCES.md');
const check = process.argv.includes('--check');

const entries = Object.values(CITATIONS).sort(
  (a, b) => a.year - b.year || a.authors.localeCompare(b.authors),
);

const primary = entries.filter((c) => c.verified === 'primary').length;

const lines = [
  '# References',
  '',
  '<!-- Generated by tools/gen-references.mjs from src/citations.js. Do not edit by hand. -->',
  '',
  'Every source behind a number that glasstext reports. Each entry records',
  'whether we read the primary source or verified the values another way, and',
  'what specifically was checked.',
  '',
  `${entries.length} sources, ${primary} read directly.`,
  '',
  '| Key | Source | Verified |',
  '| --- | --- | --- |',
  ...entries.map((c) => {
    const title = c.url ? `[${c.title}](${c.url})` : c.title;
    const loc = c.locator ? `, ${c.locator}` : '';
    return `| \`${c.id}\` | ${c.authors} (${c.year}). ${title}. *${c.source}*${loc}. | ${
      c.verified === 'primary' ? 'source read' : 'cross-checked'} |`;
  }),
  '',
  '## What we checked',
  '',
];

for (const c of entries) {
  lines.push(`### ${c.authors} (${c.year})`, '', `**${c.title}**`, '', c.note, '');
}

lines.push(
  '## On "cross-checked"',
  '',
  'Several of the readability papers are paywalled or out of print. Where we',
  'could not read the original, we did not guess: the coefficients were checked',
  "against [textstat](https://github.com/textstat/textstat)'s independent",
  'implementation and against multiple independent restatements, and the entry',
  'says so. One discrepancy found this way is documented in the Coleman–Liau',
  "entry above — textstat's docstring prints 0.058 where the published",
  'coefficient is 0.0588.',
  '',
);

const content = `${lines.join('\n')}`;

if (check) {
  let existing = '';
  try {
    existing = await readFile(OUT, 'utf8');
  } catch {
    console.error('REFERENCES.md is missing. Run: npm run gen:references');
    process.exit(1);
  }
  if (existing !== content) {
    console.error('REFERENCES.md is out of date. Run: npm run gen:references');
    process.exit(1);
  }
  console.log(`REFERENCES.md is up to date (${entries.length} sources).`);
} else {
  await writeFile(OUT, content);
  console.log(`Wrote REFERENCES.md (${entries.length} sources, ${primary} read directly).`);
}
